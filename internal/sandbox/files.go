package sandbox

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os/exec"
	"path"
	"strings"
	"time"

	"opencode-sandbox/internal/config"
)

// copyFiles seeds only new VMs, including snapshot children. Transfer to a
// missing staging path first: msb copy would otherwise nest the source basename
// inside an existing target. GNU cp -T then merges into the exact target.
func (s *Sandbox) copyFiles(ctx context.Context, settings config.Settings) error {
	for i, file := range settings.Files {
		if !file.IsCopy() {
			continue
		}
		if err := s.copyFile(ctx, file); err != nil {
			return fmt.Errorf("copy files[%d] to %q: %w", i, file.Target, err)
		}
	}
	return nil
}

func (s *Sandbox) copyFile(ctx context.Context, file config.FileSettings) (err error) {
	cli, err := runtimeCLI()
	if err != nil {
		return err
	}
	var output bytes.Buffer
	if err := s.Exec(ctx, nil, &output, nil, "mktemp", "-d", "/tmp/ocs-copy.XXXXXXXXXX"); err != nil {
		return fmt.Errorf("create guest staging directory: %w", err)
	}
	stage := strings.TrimSpace(output.String())
	if path.Dir(stage) != "/tmp" || !strings.HasPrefix(path.Base(stage), "ocs-copy.") {
		return fmt.Errorf("invalid guest staging directory %q", stage)
	}
	// Cleanup must also work after cancellation; stage is generated by mktemp.
	defer func() {
		cleanup, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		err = errors.Join(err, s.Exec(cleanup, nil, nil, nil, "rm", "-rf", "--", stage))
	}()
	cmd := exec.CommandContext(ctx, cli, "copy", "--quiet", file.Source, s.Name+":"+stage+"/source")
	if output, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("msb copy: %w: %s", err, strings.TrimSpace(string(output)))
	}
	output.Reset()
	if err := s.Exec(ctx, nil, &output, &output, "bash", "-eu", "-c", `
mkdir -p -- "$(dirname -- "$2")"
cp -aT -- "$1/source" "$2"
`, "copy-files", stage, file.Target); err != nil {
		return fmt.Errorf("merge guest copy: %w: %s", err, strings.TrimSpace(output.String()))
	}
	return nil
}
